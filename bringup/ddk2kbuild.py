#!/usr/bin/env python3
"""Turn Kleaf ddk_module() definitions into a Kbuild for a plain `make M=` build.

Usage: ddk2kbuild.py <package dir> <bzl file> <call> [options]
  <call>        the macro to run, e.g. "define_modules('lahaina', 'perf')"
  --conf FILE   CONFIG_X=y/m lines (``export`` allowed) that pick conditional_srcs
                and become -D flags; repeatable
  --set CONFIG_X=y  same, inline; repeatable
  --only NAME   only emit modules whose .ko name is NAME (repeatable)
  --cflags STR  extra ccflags-y
The package's Kbuild is replaced by the generated one.
"""
import argparse
import glob as _glob
import os
import re

ap = argparse.ArgumentParser()
ap.add_argument("pkg")
ap.add_argument("bzl")
ap.add_argument("call")
ap.add_argument("--conf", action="append", default=[])
ap.add_argument("--set", action="append", default=[])
ap.add_argument("--only", action="append", default=[])
ap.add_argument("--cflags", default="")
a = ap.parse_args()

cfg = {}
for f in a.conf:
    for line in open(f):
        m = re.match(r"\s*(?:export\s+)?(CONFIG_\w+)\s*=\s*(\S+)", line)
        if m:
            cfg[m.group(1)] = m.group(2)
for s in a.set:
    k, _, v = s.partition("=")
    cfg[k] = v or "y"

PKG = "PKGROOT"
mods = []


def select(d, **kw):
    for k, v in d.items():
        if "qtisocrepo_true" in k:
            return v
    for k, v in d.items():
        if "default" in k:
            return v
    return list(d.values())[0]


class Native:
    @staticmethod
    def package_name():
        return PKG

    @staticmethod
    def glob(patterns, **kw):
        # registries like cvp-kernel's eva_module_build.bzl glob() their
        # already-literal srcs list (no wildcards) to validate it; a real
        # glob relative to the package dir handles both that and actual
        # wildcard patterns the same way Bazel's native.glob() would.
        out = []
        for p in patterns:
            out += [os.path.relpath(m, a.pkg) for m in _glob.glob(os.path.join(a.pkg, p))]
        return out


def ddk_module(**kw):
    mods.append(kw)


class _Any:
    """Stands in for any Bazel helper: callable, any attribute."""
    def __call__(self, *a, **k):
        return _Any()

    def __getattr__(self, name):
        return _Any()


def noop(*a, **k):
    return None


class _Struct:
    """Real stand-in for Bazel's struct() -- unlike the other helpers here,
    registries like cvp-kernel's create_module_registry() actually use the
    object struct() returns (attribute access), not just its call site."""
    def __init__(self, **kw):
        self.__dict__.update(kw)


def struct(**kw):
    return _Struct(**kw)


def _type(x):
    # Starlark's type() returns a string ("list", "dict", ...); Python's
    # returns a type object. eva_module_build.bzl branches on
    # `type(x) == "list"`, which is silently always-False under real
    # Python's builtin type() -- shadow it with a Starlark-compatible one.
    if isinstance(x, bool):
        return "bool"
    if isinstance(x, list):
        return "list"
    if isinstance(x, dict):
        return "dict"
    if isinstance(x, str):
        return "string"
    if isinstance(x, int):
        return "int"
    return type(x).__name__


_loaded_bzl = set()


def load(label, *names, **kw):
    # same-package relative load (":other.bzl") -- resolve next to
    # whichever bzl file is doing the loading and exec it into the shared
    # env, same-namespace, same as Starlark's module-level load() does.
    # Absolute/cross-package labels ("//other/pkg:x.bzl") aren't needed by
    # anything converted so far and are silently skipped.
    name = label.split(":")[-1]
    if not label.startswith(":") and not label.startswith(os.path.dirname(a.bzl)):
        return
    path = os.path.join(os.path.dirname(os.path.abspath(a.bzl)), name)
    if path in _loaded_bzl or not os.path.exists(path):
        return
    _loaded_bzl.add(path)
    exec(compile(open(path).read(), path, "exec"), env)


env = {
    "load": load, "select": select, "native": Native, "ddk_module": ddk_module,
    "ddk_headers": noop, "copy_to_dist_dir": noop, "pkg_files": noop,
    "pkg_install": noop, "strip_prefix": _Any(), "genrule": noop, "Label": str,
    "kernel_module_group": noop,
    "True": True, "False": False, "struct": struct, "type": _type,
}
src = open(a.bzl).read()
exec(compile(src, a.bzl, "exec"), env)
exec(a.call, env)


def on(opt):
    return cfg.get(opt, "n") in ("y", "m")


def fix(s):
    # absolute: define_trace.h resolves TRACE_INCLUDE_PATH from include/trace
    return re.sub(r"(\.\./)*" + PKG, os.path.abspath(a.pkg), s)


out = ["# Generated by ddk2kbuild.py from %s: %s" % (os.path.basename(a.bzl), a.call)]
flags = []
for k, v in sorted(cfg.items()):
    if v == "y":
        flags.append("-D%s=1" % k)
    elif v == "m":
        flags.append("-D%s_MODULE=1" % k)
out.append("ccflags-y += " + " ".join(flags) + " " + a.cflags)
emitted = []
for m in mods:
    ko = m["out"]
    name = ko[:-3]
    if a.only and name not in a.only:
        continue
    files = list(m.get("srcs", []))
    for opt, val in (m.get("conditional_srcs") or {}).items():
        files += val.get(on(opt), []) if isinstance(val, dict) else (val if on(opt) else [])
    objs, seen = [], set()
    for f in files:
        if f.endswith(".c") and f not in seen:
            seen.add(f)
            objs.append(f[:-2] + ".o")
    if not objs:
        continue
    out.append("")
    out.append("obj-m += %s.o" % name)
    out.append("%s-y := %s" % (name, " ".join(objs)))
    mflags = []
    for d in m.get("local_defines", []) or []:
        mflags.append("-D" + fix(d))
    for i in m.get("includes", []) or []:
        mflags.append("-I$(src)/" + i)
    mflags += m.get("copts", []) or []
    for o in objs:
        dirs = {os.path.dirname(o)}
        out.append("CFLAGS_%s := %s %s" % (o, " ".join(mflags), " ".join("-I$(src)/" + x for x in dirs if x)))
    emitted.append(ko)
open(os.path.join(a.pkg, "Kbuild"), "w").write("\n".join(out) + "\n")
mk = os.path.join(a.pkg, "Makefile")
if os.path.exists(mk):
    os.rename(mk, mk + ".orig")
print("modules:", " ".join(emitted))
