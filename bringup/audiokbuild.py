#!/usr/bin/env python3
"""Turn audio-kernel's Bazel module registry (audio_modules.bzl + build/lahaina.bzl)
into a Kbuild for a plain `make M=` build. Usage: audiokbuild.py <audio-kernel dir>"""
import os, sys

root = sys.argv[1]
modules = {}


class Registry:
    def __init__(self, hdrs=()):
        self.hdrs = list(hdrs)

    def register(self, name, path=None, config_option=None, srcs=(), conditional_srcs=None, deps=()):
        modules[name] = dict(path=path or "", config_option=config_option, srcs=list(srcs),
                             conditional_srcs=conditional_srcs or {}, deps=list(deps))


env = {"load": lambda *a, **k: None, "create_module_registry": lambda hdrs=(): Registry(hdrs),
       "True": True, "False": False}
exec(open(os.path.join(root, "audio_modules.bzl")).read(), env)

target = {}


def define_target_modules(target_name=None, variants=None, registry=None, modules=None, config_options=None, **kw):
    target.update(modules=modules, options=config_options)


env2 = {"load": lambda *a, **k: None, "define_target_modules": define_target_modules,
        "audio_modules": env["audio_modules"], "True": True, "False": False}
src = open(os.path.join(root, "build", "lahaina.bzl")).read()
exec(src, env2)
env2["define_lahaina"]()

options = set(target["options"])
for _n in target["modules"]:
    if modules.get(_n, {}).get("config_option"):
        options.add(modules[_n]["config_option"])
out = ["# Generated by audiokbuild.py from audio_modules.bzl and build/lahaina.bzl",
       "AUDIO_ROOT := $(src)",
       "ccflags-y += -I$(AUDIO_ROOT)/include -I$(AUDIO_ROOT)/include/uapi -I$(AUDIO_ROOT)/include/uapi/audio \\",
       "\t-I$(AUDIO_ROOT)/config -I$(AUDIO_ROOT)/asoc -I$(AUDIO_ROOT)/asoc/codecs -I$(AUDIO_ROOT)/dsp \\",
       "\t-I$(AUDIO_ROOT)/ipc -I$(AUDIO_ROOT)/soc -I$(AUDIO_ROOT)/dsp/codecs"]
for o in sorted(options):
    out.append("ccflags-y += -D%s=1" % o)
out.append("")
missing = []
for name in target["modules"]:
    m = modules.get(name)
    if not m:
        missing.append(name)
        continue
    files = list(m["srcs"])
    for opt, val in m["conditional_srcs"].items():
        if isinstance(val, list):
            val = {True: val}
        files += val.get(opt in options, [])
    seen, objs = set(), []
    for f in files:
        if not f.endswith(".c") or f in seen:
            continue
        seen.add(f)
        objs.append(os.path.join(m["path"], f[:-2] + ".o"))
    if not objs:
        continue
    out.append("obj-m += %s.o" % name)
    out.append("%s-y := %s" % (name, " ".join(objs)))
    dirs = sorted({os.path.dirname(o) for o in objs})
    for o in objs:
        out.append("CFLAGS_%s := -I$(AUDIO_ROOT)/%s" % (o, os.path.dirname(o)))
    out.append("")
open(os.path.join(root, "Kbuild"), "w").write("\n".join(out) + "\n")
print("modules:", sum(1 for l in out if l.startswith("obj-m")), "missing:", missing)
